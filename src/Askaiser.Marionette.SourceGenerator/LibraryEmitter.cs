using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;

namespace Askaiser.Marionette.SourceGenerator;

/// <summary>
/// Writes the C# code of an image library.
/// </summary>
/// <remarks>
/// <para>
/// Images are embedded as base64 text. With C# 11 and later they are UTF-8 string literals, which the compiler stores
/// as static data in the assembly: an image costs nothing until it is used, and does not go through a .NET string.
/// </para>
/// <para>
/// Elements are created on first use and shared by every instance of the library.
/// </para>
/// </remarks>
internal sealed class LibraryEmitter
{
    private const string ImagesClassName = "__Images";
    private const string ElementType = "global::Askaiser.Marionette.ImageElement";
    private const string ElementInterface = "global::Askaiser.Marionette.IElement";

    private static readonly string GeneratedCodeAttribute =
        "[global::System.CodeDom.Compiler.GeneratedCodeAttribute(\"" + typeof(LibraryEmitter).Assembly.GetName().Name + "\", \"" + typeof(LibraryEmitter).Assembly.GetName().Version + "\")]";

    private readonly LibraryTarget _target;
    private readonly StringBuilder _code = new StringBuilder();
    private readonly List<ImageEntry> _images = [];
    private readonly Dictionary<ImageEntry, int> _imageIds = [];
    private int _indentation;

    public LibraryEmitter(LibraryTarget target)
    {
        this._target = target;
    }

    public string Emit(LibraryNode root)
    {
        this.Line("// <auto-generated/>");
        this.Line("#nullable enable");
        this.Line();

        var hasNamespace = this._target.Namespace.Length > 0;
        if (hasNamespace)
        {
            this.Line("namespace " + this._target.Namespace);
            this.OpenBlock();
        }

        this.Line("partial class " + this._target.ClassName);
        this.OpenBlock();

        this.Line(GeneratedCodeAttribute);
        this.Line("private static " + this._target.ClassName + "? __instance;");
        this.Line();
        this.Line("/// <summary>Gets a shared instance of this image library.</summary>");
        this.Line(GeneratedCodeAttribute);
        this.Line("public static " + this._target.ClassName + " Instance => __instance ??= new " + this._target.ClassName + "();");

        this.EmitMembers(root);
        this.EmitImages();

        this.CloseBlock();

        if (hasNamespace)
        {
            this.CloseBlock();
        }

        return this._code.ToString();
    }

    private static string DescribeImage(ImageEntry image)
    {
        var description = new StringBuilder("<c>" + Escape(image.File.RelativePath) + "</c>");

        if (TryReadPngSize(image.Content, out var width, out var height))
        {
            description.Append(" (").Append(width.ToString(CultureInfo.InvariantCulture)).Append('x').Append(height.ToString(CultureInfo.InvariantCulture)).Append(" pixels)");
        }

        return description.ToString();
    }

    private static string DescribeOptions(ImageEntry image)
    {
        var threshold = image.Threshold.ToString(CultureInfo.InvariantCulture);
        return image.Grayscale ? $"Searched in grayscale with a threshold of {threshold}." : $"Searched with a threshold of {threshold}.";
    }

    private static string Escape(string text)
    {
        return text.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");
    }

    private static bool TryReadPngSize(byte[] content, out int width, out int height)
    {
        width = height = 0;

        // A PNG file starts with an 8-byte signature followed by its header chunk, which begins with the image size.
        if (content.Length < 24 || content[0] != 0x89 || content[1] != 0x50 || content[2] != 0x4E || content[3] != 0x47)
        {
            return false;
        }

        width = (content[16] << 24) | (content[17] << 16) | (content[18] << 8) | content[19];
        height = (content[20] << 24) | (content[21] << 16) | (content[22] << 8) | content[23];
        return width > 0 && height > 0;
    }

    private void EmitMembers(LibraryNode library)
    {
        var children = library.Children.Values.Where(static child => !child.IsEmpty).ToList();

        foreach (var child in children)
        {
            this.Line();
            this.Line("/// <summary>Gets the images of the <c>" + Escape(string.Join("/", child.Path)) + "</c> library.</summary>");
            this.Line(GeneratedCodeAttribute);
            this.Line("public " + child.TypeName + " " + child.Name + " { get; } = new " + child.TypeName + "();");
        }

        foreach (var group in library.Images.Values)
        {
            this.Line();

            if (group.Count == 1)
            {
                var image = group[0];
                this.Line("/// <summary>Gets the image " + DescribeImage(image) + ". " + DescribeOptions(image) + "</summary>");
                this.Line(GeneratedCodeAttribute);
                this.Line("public " + ElementInterface + " " + image.Name + " => " + ImagesClassName + "." + this.GetImageMember(image) + ";");
            }
            else
            {
                this.Line("/// <summary>Gets the " + group.Count.ToString(CultureInfo.InvariantCulture) + " images " + string.Join(", ", group.Select(DescribeImage)) + ". Use them with methods that accept several elements.</summary>");
                this.Line(GeneratedCodeAttribute);
                this.Line("public " + ElementInterface + "[] " + group[0].Name + " => new " + ElementInterface + "[]");
                this.Line("{");
                this._indentation++;

                foreach (var image in group)
                {
                    this.Line(ImagesClassName + "." + this.GetImageMember(image) + ",");
                }

                this._indentation--;
                this.Line("};");
            }
        }

        foreach (var child in children)
        {
            this.Line();
            this.Line("/// <summary>The images of the <c>" + Escape(string.Join("/", child.Path)) + "</c> library.</summary>");
            this.Line(GeneratedCodeAttribute);
            this.Line("public sealed class " + child.TypeName);
            this.OpenBlock();
            this.Line("internal " + child.TypeName + "()");
            this.Line("{");
            this.Line("}");
            this.EmitMembers(child);
            this.CloseBlock();
        }
    }

    private string GetImageMember(ImageEntry image)
    {
        if (!this._imageIds.TryGetValue(image, out var id))
        {
            id = this._images.Count;
            this._imageIds.Add(image, id);
            this._images.Add(image);
        }

        return "E" + id.ToString(CultureInfo.InvariantCulture);
    }

    private void EmitImages()
    {
        this.Line();
        this.Line(GeneratedCodeAttribute);
        this.Line("private static class " + ImagesClassName);
        this.OpenBlock();

        for (var id = 0; id < this._images.Count; id++)
        {
            var image = this._images[id];
            var suffix = id.ToString(CultureInfo.InvariantCulture);

            if (id > 0)
            {
                this.Line();
            }

            var arguments = ", " + image.Threshold.ToString(CultureInfo.InvariantCulture) + "m, " + (image.Grayscale ? "true" : "false") + ")";
            var content = Convert.ToBase64String(image.Content);

            this.Line("private static " + ElementType + "? _e" + suffix + ";");
            this.Line();

            // A race between two threads creates the element twice at worst, which is harmless.
            if (this._target.SupportsUtf8Literals)
            {
                this.Line("internal static " + ElementType + " E" + suffix + " => _e" + suffix + " ??= " + ElementType + ".FromBase64(\"" + image.ElementName + "\", \"" + content + "\"u8" + arguments + ";");
            }
            else
            {
                this.Line("internal static " + ElementType + " E" + suffix + " => _e" + suffix + " ??= new " + ElementType + "(\"" + image.ElementName + "\", \"" + content + "\"" + arguments + ";");
            }
        }

        this.CloseBlock();
    }

    private void OpenBlock()
    {
        this.Line("{");
        this._indentation++;
    }

    private void CloseBlock()
    {
        this._indentation--;
        this.Line("}");
    }

    private void Line(string text = "")
    {
        if (text.Length > 0)
        {
            this._code.Append(' ', this._indentation * 4).Append(text);
        }

        this._code.Append('\n');
    }
}
